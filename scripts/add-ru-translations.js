const calcFilePath = path.resolve('src/data/calculators.ts');
let content = fs.readFileSync(calcFilePath, 'utf8');

for (const [id, ruData] of Object.entries(ruCalculators)) {
  // Regex to find the calculator block in dynamicTranslations
  const regex = new RegExp(`("${id}":\\s*{[\\s\\S]*?ar:\\s*{[^}]*}\\s*,?)(\\s*)`, 'm');
  const match = content.match(regex);
  if (match) {
    if (!match[0].includes('ru:')) {
      const ruLine = `\n    ru: { title: "${ruData.title}", description: "${ruData.description}" },`;
      content = content.replace(regex, `$1${ruLine}$2`);
    }
  } else {
    console.warn(`Warning: Could not match block for ${id}`);
  }
}

fs.writeFileSync(calcFilePath, content, 'utf8');
console.log('Successfully updated src/data/calculators.ts with Russian translations.');
